// Writes two reviewer documents from the bundled English curriculum:
//   docs/curriculum/SCREEN_LOCATOR.md   display "Module N, Step M" (as the app shows it) next to each internal screen ID
//   docs/curriculum/SOURCE_CITATIONS.md the PubMed "Supporting source" citations and the statements they could not support
// Run: npx tsx scripts/generate-curriculum-locator.ts   (tests/citations.test.ts fails if either file is stale)
import { writeFileSync } from 'node:fs';
import { CITATION_CONFLICTS, SCREEN_CITATIONS, citationLabel, pubmedUrl } from '../src/content/citations';
import { getModules } from '../src/content';

const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');

export function screenLocations() {
  return getModules('en').flatMap((module, moduleIndex) => module.screens.map((screen, screenIndex) => ({
    displayModule: moduleIndex + 1, step: screenIndex + 1, steps: module.screens.length, moduleTitle: module.title, screen,
  })));
}

const where = (screenId: string) => {
  const found = screenLocations().find((location) => location.screen.id === screenId);
  if (!found) throw new Error(`Unknown screen ${screenId}`);
  return found;
};

export function screenLocatorMarkdown(): string {
  const lines = [
    '# Screen locator',
    '',
    'Generated by `scripts/generate-curriculum-locator.ts` from the English curriculum. "Module" and "Step" are the numbers the app shows (for example "Module 3, Step 2 of 19"). The internal ID is what the code, translations, and answer keys use.',
    '',
  ];
  let current = 0;
  for (const location of screenLocations()) {
    if (location.displayModule !== current) {
      current = location.displayModule;
      lines.push(`## Module ${current}: ${location.moduleTitle}`, '', '| Step | Internal ID | Type | Title |', '| --- | --- | --- | --- |');
    }
    const { screen } = location;
    lines.push(`| ${location.step} of ${location.steps} | \`${screen.id}\` | ${screen.type} | ${cell(screen.title)} |`);
    if (location.step === location.steps) lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

export function sourceCitationsMarkdown(): string {
  const citations = Object.entries(SCREEN_CITATIONS).map(([screenId, citation]) => ({ ...where(screenId), citation }))
    .sort((a, b) => a.displayModule - b.displayModule || a.step - b.step);
  const content = screenLocations().filter((location) => location.screen.type === 'content').length;
  const lines = [
    '# Supporting-source citations',
    '',
    `Generated by \`scripts/generate-curriculum-locator.ts\` from \`src/content/citations.ts\`. ${citations.length} of ${content} content screens (${Math.round((citations.length / content) * 100)}%) show a "Supporting source" link to a PubMed-indexed paper. Every module has at least one.`,
    '',
    'How each citation was checked (2026-11-22): the paper was fetched from PubMed through NCBI E-utilities; the supporting sentence below appears word for word in its abstract; the cited statement appears word for word on the screen (`tests/citations.test.ts` keeps checking this); and the PubMed page opens. Nothing was cited from memory. Sources were not clinically reviewed.',
    '',
    'The existing NHLBI link on Module 1, Steps 1 and 8 is official health information, not a paper, and stays as it was.',
    '',
    '| Module, step | Statement on the screen | Source shown in the app | Study type | Supporting sentence from the abstract | Reviewer note |',
    '| --- | --- | --- | --- | --- | --- |',
    ...citations.map(({ displayModule, step, citation }) => `| ${displayModule}, ${step} | ${cell(citation.claim)} | [${cell(citationLabel(citation))}](${pubmedUrl(citation.pmid)}) (PMID ${citation.pmid}) | ${citation.studyType} | ${cell(citation.supportingQuote)} | ${cell(citation.reviewNote ?? '')} |`),
    '',
    '## Statements the evidence does not support as written',
    '',
    'These come from the CIAS text and were left unchanged. They need the content owner\'s decision (and clinical review) before anything is cited there.',
    '',
    '| Module, step | Wording on the screen | Papers | What the papers say |',
    '| --- | --- | --- | --- |',
    ...CITATION_CONFLICTS.map((conflict) => {
      const location = where(conflict.screenId);
      return `| ${location.displayModule}, ${location.step} | "${cell(conflict.claim)}" | ${conflict.pmids.map((pmid) => `[PMID ${pmid}](${pubmedUrl(pmid)})`).join(', ')} | ${cell(conflict.issue)} |`;
    }),
  ];
  return `${lines.join('\n')}\n`;
}

if (process.argv[1] && /generate-curriculum-locator/.test(process.argv[1])) {
  writeFileSync('docs/curriculum/SCREEN_LOCATOR.md', screenLocatorMarkdown(), 'utf8');
  writeFileSync('docs/curriculum/SOURCE_CITATIONS.md', sourceCitationsMarkdown(), 'utf8');
  console.log('Wrote docs/curriculum/SCREEN_LOCATOR.md and docs/curriculum/SOURCE_CITATIONS.md');
}
