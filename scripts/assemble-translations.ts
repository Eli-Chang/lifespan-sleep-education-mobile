// Assembles the reviewed working files under artifacts/translation-work/<locale>/ (lesson chunks plus
// ui-media.json) into the committed catalog src/content/translations/<locale>.ts. The catalog is the source of
// truth after assembly; the working files are git-ignored scratch.
//
//   npx tsx scripts/assemble-translations.ts pt-BR ht
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const exportName = (locale: string) => locale.replace(/-(\w)/g, (_, letter: string) => letter.toUpperCase()).replace(/^(\w)/, (letter) => letter.toLowerCase()) + 'Catalog';

for (const locale of process.argv.slice(2)) {
  const dir = join('artifacts', 'translation-work', locale);
  if (!existsSync(dir)) throw new Error(`No working folder ${dir}`);
  const content: Record<string, string> = {};
  for (const file of readdirSync(dir).filter((name) => /^chunk-[A-Z]\.json$/.test(name)).sort()) {
    for (const [key, value] of Object.entries(JSON.parse(readFileSync(join(dir, file), 'utf8')) as Record<string, string>)) {
      if (key in content) throw new Error(`${locale}: duplicate unit ${key} in ${file}`);
      content[key] = value.normalize('NFC');
    }
  }
  const uiMedia = JSON.parse(readFileSync(join(dir, 'ui-media.json'), 'utf8')) as { ui: Record<string, string>; media: Record<string, string> };
  const ui = Object.fromEntries(Object.entries(uiMedia.ui).map(([key, value]) => [key.replace(/^ui:/, ''), value.normalize('NFC')]));
  const media = Object.fromEntries(Object.entries(uiMedia.media).map(([key, value]) => [key, value.normalize('NFC')]));
  const sorted = (record: Record<string, string>) => Object.fromEntries(Object.entries(record).sort(([a], [b]) => a.localeCompare(b)));
  const out = `// Generated by scripts/assemble-translations.ts from Claude-drafted working files. Do not edit by hand without
// recording the change in docs/translation/TRANSLATION_QA.md. Status: AI draft, not reviewed by a qualified
// translator or a clinician. Keys are unit IDs from scripts/export-translation-source.ts.
import type { UiKey } from '@/src/i18n/strings';

export const ${exportName(locale)}: {
  content: Readonly<Record<string, string>>;
  ui: Readonly<Record<UiKey, string>>;
  media: Readonly<Record<string, string>>;
} = ${JSON.stringify({ content: sorted(content), ui: sorted(ui), media: sorted(media) }, null, 2)};
`;
  writeFileSync(join('src', 'content', 'translations', `${locale}.ts`), out);
  console.log(`${locale}: ${Object.keys(content).length} lesson units, ${Object.keys(ui).length} UI strings, ${Object.keys(media).length} media strings`);
}
